# Python Casting

# Integer casting
x = int(1)
y = int(2.8)
z = int("3")

print(x)
print(y)
print(z)

# Float casting
a = float(1)
b = float(2.8)
c = float("3")
d = float("4.2")

print(a)
print(b)
print(c)
print(d)

# String casting
p = str("s1")
q = str(2)
r = str(3.0)

print(p)
print(q)
print(r)

