# Python Math

import math


# 1. min()
smallest = min(5, 10, 25)
print("Minimum:", smallest)


# 2. max()
largest = max(5, 10, 25)
print("Maximum:", largest)


# 3. abs()
absolute_value = abs(-7.25)
print("Absolute value:", absolute_value)


# 4. pow()
power = pow(4, 3)
print("Power:", power)


# 5. sqrt()
square_root = math.sqrt(64)
print("Square root:", square_root)


# 6. ceil()
up_value = math.ceil(1.4)
print("Ceil:", up_value)


# 7. floor()
down_value = math.floor(1.4)
print("Floor:", down_value)


# 8. pi
print("PI:", math.pi)


# 9. More practice
print("Minimum:", min(15, 7, 25, 3))
print("Maximum:", max(15, 7, 25, 3))
print("Absolute:", abs(-100))
print("Power:", pow(2, 5))
print("Square root:", math.sqrt(81))
print("Ceil:", math.ceil(4.2))
print("Floor:", math.floor(4.8))